"""Generate the runtime's import tables and logging stubs.

Usage: python -I tools/gen_imports.py <recomp_dir>

Inputs:  build/imports.txt         (from: xexdump game/Default.xex --imports)
         runtime/*.cpp             (IMPORT(Name) blocks = implemented imports)
Outputs: runtime/generated/import_func_slots.inc   IAT slot -> thunk address
         runtime/generated/import_vars.inc         kernel variable slots
         runtime/generated/import_stubs.cpp        stubs for unimplemented imports
"""
import glob
import os
import re
import sys

root = sys.argv[1] if len(sys.argv) > 1 else "."
lines = open(os.path.join(root, "build", "imports.txt"), encoding="utf-8").read().splitlines()

thunks = {}       # export name -> thunk address
slots = []        # (slot, name) records of type 0
for line in lines:
    parts = line.split()
    if not parts:
        continue
    kind, lib, addr, name = parts[0], parts[1], int(parts[2], 16), parts[3]
    if name.startswith("__imp__"):
        name = name[len("__imp__"):]
    if kind == "FUNC":
        thunks[name] = addr
    else:
        slots.append((addr, name, lib))

implemented = set()
for path in glob.glob(os.path.join(root, "runtime", "*.cpp")):
    implemented.update(re.findall(r"^\s*IMPORT\((\w+)\)", open(path, encoding="utf-8").read(), re.M))

out_dir = os.path.join(root, "runtime", "generated")
os.makedirs(out_dir, exist_ok=True)

with open(os.path.join(out_dir, "import_func_slots.inc"), "w", encoding="utf-8") as f:
    f.write("// GENERATED by tools/gen_imports.py\n")
    for addr, name, lib in slots:
        if name in thunks:
            f.write("IMPORT_FUNC_SLOT(0x%08X, 0x%08X, %s)\n" % (addr, thunks[name], name))

with open(os.path.join(out_dir, "import_vars.inc"), "w", encoding="utf-8") as f:
    f.write("// GENERATED by tools/gen_imports.py\n")
    for addr, name, lib in slots:
        if name not in thunks:
            f.write("IMPORT_VAR(0x%08X, %s)\n" % (addr, name))

missing = sorted(n for n in thunks if n not in implemented)
with open(os.path.join(out_dir, "import_stubs.cpp"), "w", encoding="utf-8") as f:
    f.write("// GENERATED by tools/gen_imports.py: logging stubs for imports without IMPORT().\n")
    f.write("// Each stub logs its first calls with r3-r6 and returns 0 (STATUS_SUCCESS).\n")
    f.write('#include "../runtime.h"\n\n')
    f.write("static void StubLog(const char* name, std::atomic<int>& count, PPCContext& ctx)\n{\n")
    f.write("    int n = count++;\n")
    f.write("    if (n < 8)\n")
    f.write('        Log("[stub] %s(0x%08X, 0x%08X, 0x%08X, 0x%08X)%s", name, ctx.r3.u32, ctx.r4.u32, ctx.r5.u32, ctx.r6.u32, n == 7 ? " (further calls not logged)" : "");\n')
    f.write("    ctx.r3.u64 = 0;\n}\n\n")
    for n in missing:
        f.write("static std::atomic<int> s_%s;\n" % n)
        f.write("IMPORT(%s) { (void)base; StubLog(\"%s\", s_%s, ctx); }\n" % (n, n, n))

print("imports: %d functions (%d implemented, %d stubbed), %d variables"
      % (len(thunks), len(thunks) - len(missing), len(missing), sum(1 for _, n, _ in slots if n not in thunks)))
