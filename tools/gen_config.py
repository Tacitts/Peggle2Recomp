"""Build config/peggle2.toml from peggle2.base.toml + generated function bounds.

Usage: python -I tools/gen_config.py <recomp_dir>
"""
import os
import sys

root = sys.argv[1] if len(sys.argv) > 1 else "."
cfg = os.path.join(root, "config")
base = open(os.path.join(cfg, "peggle2.base.toml"), encoding="utf-8").read()
funcs_path = os.path.join(cfg, "peggle2_functions.toml")
funcs = open(funcs_path, encoding="utf-8").read() if os.path.exists(funcs_path) else "functions = []\n"
lines = [l for l in base.splitlines() if "@FUNCTIONS@" not in l]
out = []
for l in base.splitlines():
    if "@FUNCTIONS@" in l:
        out.append(funcs.rstrip())
    else:
        out.append(l)
header = "# GENERATED by tools/gen_config.py - edit peggle2.base.toml instead.\n"
open(os.path.join(cfg, "peggle2.toml"), "w", encoding="utf-8").write(header + "\n".join(out) + "\n")
print("wrote", os.path.join(cfg, "peggle2.toml"))
